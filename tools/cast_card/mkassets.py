"""Generate build-time assets: fonts, default theme, VMU icon, theme packs.
Run from repo root (build.sh does it)."""
import os, sys, struct
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", ".."))
from tools.cast_card import mkfont, tex, themes, mkconsole
from PIL import Image, ImageDraw

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
RD = os.path.join(ROOT, "assets", "romdisk")
TTF = os.path.join(ROOT, "assets", "fonts", "Dreamcast.ttf")   # NiseSegaDreamcast, the Dreamcast logotype lookalike

def fonts():
    os.makedirs(os.path.join(RD, "font"), exist_ok=True)
    mkfont.build(TTF, 18, os.path.join(RD, "font", "ui"), stroke=0)
    mkfont.build(TTF, 26, os.path.join(RD, "font", "ui_big"), stroke=1)
    mkfont.build(TTF, 14, os.path.join(RD, "font", "ui_small"), stroke=0)
    mkfont.build(TTF, 42, os.path.join(RD, "font", "ui_display"), stroke=2, atlas=(512, 512))

BRAND = os.path.join(ROOT, "assets", "brand", "icon_transparent.png")

def logo(path, size=64):
    """Brand icon (assets/brand) -> ARGB4444 .tex; falls back to a drawn placeholder."""
    if os.path.exists(BRAND): img = Image.open(BRAND).convert("RGBA").resize((size, size), Image.LANCZOS)
    else:
        img = Image.new("RGBA", (size, size), (0, 0, 0, 0)); d = ImageDraw.Draw(img)
        d.rounded_rectangle([0, 0, size - 1, size - 1], radius=size // 5, fill=(46, 200, 255, 255))
        d.ellipse([size * 0.2, size * 0.2, size * 0.8, size * 0.8], outline=(255, 255, 255, 255), width=max(2, size // 12))
    with open(path, "wb") as f: f.write(tex.encode(img, "argb4444"))

def theme_packs():
    """themes/<id>/theme.ini + bg.png (editable by users); romdisk gets the default as .tex."""
    for tid, spec in themes.THEMES.items():
        d = os.path.join(ROOT, "themes", tid); os.makedirs(d, exist_ok=True)
        themes.write_ini(spec, os.path.join(d, "theme.ini"))
        themes.render_bg(spec).save(os.path.join(d, "bg.png"))
        if os.path.exists(BRAND): Image.open(BRAND).convert("RGBA").resize((64, 64), Image.LANCZOS).save(os.path.join(d, "logo.png"))
    dd = os.path.join(RD, "themes", "default"); os.makedirs(dd, exist_ok=True)
    spec = dict(themes.THEMES["dreamcast"], name="Dreamcast")
    themes.write_ini(spec, os.path.join(dd, "theme.ini"))
    with open(os.path.join(dd, "bg.tex"), "wb") as f: f.write(tex.encode(themes.render_bg(spec).resize((512, 512)), "rgb565"))
    logo(os.path.join(dd, "logo.tex"))

def sfx():
    """Three short UI sounds (16-bit mono 22050 Hz WAV): move = tick, select = two-note chirp, back = soft down-blip."""
    import math, struct, wave
    d = os.path.join(RD, "sfx"); os.makedirs(d, exist_ok=True)
    def tone(spec, name):
        rate = 22050; out = []
        for freq, ms, vol in spec:
            n = int(rate * ms / 1000)
            for i in range(n):
                env = min(1.0, i / (rate * 0.003)) * (1 - i / n) ** 1.6
                out.append(int(32767 * vol * env * math.sin(2 * math.pi * freq * i / rate)))
        with wave.open(os.path.join(d, name + ".wav"), "wb") as w:
            w.setnchannels(1); w.setsampwidth(2); w.setframerate(rate); w.writeframes(struct.pack("<%dh" % len(out), *out))
    tone([(1400, 28, 0.35)], "move")
    tone([(880, 45, 0.4), (1320, 90, 0.4)], "select")
    tone([(700, 40, 0.35), (480, 90, 0.3)], "back")

def vmu_icon():
    """32x32 4-bit paletted icon as KOS vmu_pkg expects (ARGB4444 palette): brand icon on navy."""
    bg = (242, 242, 239)
    if os.path.exists(BRAND):
        src = Image.open(BRAND).convert("RGBA").resize((28, 28), Image.LANCZOS)
        canvas = Image.new("RGB", (32, 32), bg); canvas.paste(src, (2, 2), src)
        img = canvas.quantize(colors=16, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
        pal = [tuple(img.getpalette()[i * 3:i * 3 + 3]) for i in range(16)]
    else:
        img = Image.new("P", (32, 32)); d = ImageDraw.Draw(img)
        pal = [bg, (46, 200, 255), (255, 255, 255), (14, 15, 20)] + [(0, 0, 0)] * 12
        img.putpalette(sum(pal, ()))
        d.rounded_rectangle([1, 1, 30, 30], radius=6, fill=1); d.ellipse([7, 7, 24, 24], outline=2, width=3)
    px = img.tobytes()
    data = bytes((px[i] << 4) | px[i + 1] for i in range(0, 1024, 2))
    pal16 = [0xF000 | (r >> 4) << 8 | (g >> 4) << 4 | (b >> 4) for (r, g, b) in pal]
    with open(os.path.join(ROOT, "src", "vmu_icon.c"), "w") as f:
        f.write("/* generated by tools/cast_card/mkassets.py */\n#include <stdint.h>\n")
        f.write("const uint16_t cast_vmu_pal[16] = {" + ",".join(f"0x{v:04X}" for v in pal16) + "};\n")
        f.write("uint8_t cast_vmu_icon[512] = {" + ",".join(str(b) for b in data) + "};\n")

if __name__ == "__main__":
    fonts(); theme_packs(); vmu_icon(); sfx(); mkconsole.build(os.path.join(RD, "console"))
    print("assets ok")
