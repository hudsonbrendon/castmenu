"""assets/lang/strings.tsv (UTF-8) -> src/ui/lang_table.c (Latin-1 escaped) + src/ui/lang_ids.h."""
import csv, os

LANGS = ["pt", "en", "es", "de", "fr", "it"]

def esc(s):
    out = []
    for ch in s:
        b = ch.encode("latin-1", "replace")[0]
        if ch in '"\\': out.append("\\" + ch)
        elif 32 <= b < 127: out.append(ch)
        else: out.append("\\x%02x\" \"" % b)   # split so a following hex digit is not eaten
    return '"' + "".join(out) + '"'

def build(tsv, out_c, out_h):
    rows = list(csv.DictReader(open(tsv, encoding="utf-8"), delimiter="\t"))
    ids = [r["id"] for r in rows]
    with open(out_h, "w") as h:
        h.write("/* generated by tools/cast_card/mklang.py */\n#pragma once\ntypedef enum {\n")
        for i in ids: h.write(f"    S_{i},\n")
        h.write("    S_COUNT\n} str_id;\n#define LANG_COUNT %d\n" % len(LANGS))
    with open(out_c, "w") as c:
        c.write("/* generated by tools/cast_card/mklang.py */\n#include \"lang_ids.h\"\n")
        c.write("const char *const lang_names[LANG_COUNT] = { \"Portugu\\xea\" \"s\", \"English\", \"Espa\\xf1\" \"ol\", \"Deutsch\", \"Fran\\xe7\" \"ais\", \"Italiano\" };\n")
        c.write("const char *const lang_codes[LANG_COUNT] = { %s };\n" % ", ".join('"%s"' % l for l in LANGS))
        c.write("const char *const lang_table[LANG_COUNT][S_COUNT] = {\n")
        for l in LANGS:
            c.write("  {\n")
            for r in rows: c.write("    %s,\n" % esc(r[l] or r["en"]))
            c.write("  },\n")
        c.write("};\n")
    return len(ids)

if __name__ == "__main__":
    root = os.path.join(os.path.dirname(__file__), "..", "..")
    n = build(os.path.join(root, "assets", "lang", "strings.tsv"), os.path.join(root, "src", "ui", "lang_table.c"), os.path.join(root, "src", "ui", "lang_ids.h"))
    print("lang ok", n)
